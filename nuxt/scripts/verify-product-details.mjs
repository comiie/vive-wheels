const root = fileURLToPath(new URL('../.output/public/', import.meta.url))
for (const route of ['product/street/vi-1', 'product/accessories/zinc-lug-nuts']) {
  const html = readFileSync(resolve(root, route, 'index.html'), 'utf8')
  assert.match(html, /data-ssr="true"/)
  assert.doesNotMatch(html, /www\.figma\.com\/api\/mcp\/asset|finish image coming soon/)
  for (const phrase of ['detail-hero','product-faq','related-accessories','inner-upgrade','Decrease quantity','Increase quantity','SUBMIT','Search product FAQs']) assert.ok(html.includes(phrase), phrase)
  assert.equal((html.match(/class="related-card"/g)||[]).length,5)
  assert.ok(html.includes('data-reveal="words"'))
  const assets = new Set([...html.matchAll(/\/assets\/[\w./-]+\.(?:webp|svg)/g)].map(m=>m[0]))
  for (const asset of assets) assert.ok(statSync(resolve(root, '.'+asset)).size>0,asset)
  if (route.includes('street')) {
    for (const title of ['Engineered Beyond Design.','VI-1 Specifications','Performance, Refined For The Road.','Every Detail Has A Purpose.','Gallery']) assert.ok(html.includes(title), title)
    assert.equal((html.match(/class="detail-editorial-section(?: [^"]*)?"/g)||[]).length,7)
    for (const component of ['performance-story', 'performance-copy', 'detail-craft', 'craft-card', 'product-gallery-column']) assert.ok(html.includes(component), component)
    assert.equal((html.match(/class="craft-card"/g)||[]).length, 3)
    assert.equal((html.match(/class="product-gallery-column"/g)||[]).length, 4)
    assert.match(html,/aria-label="Wheel size"/)
  } else { assert.match(html,/Applicable models/); assert.match(html,/Precision Fitment/); assert.match(html,/\$128/); }
  console.log(`PASS ${route}: SSR, interactions, section content, ${assets.size} local assets`)
}
